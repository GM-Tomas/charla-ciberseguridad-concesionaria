export function formatPresenterNotes(g: SlideGuide): string {
  return [
    `BLOQUE ${g.blockIndex} · ${g.blockTitle} (${g.blockMinutes} min | ${g.timeWindow})`,
    '',
    `QUÉ DECIR:`,
    g.say,
    '',
    `NO OLVIDAR:`,
    `→ ${g.keyTakeaway}`,
    '',
    `PUENTE A LA SIGUIENTE:`,
    `"${g.bridge}"`,
  ].join('\n');
}
